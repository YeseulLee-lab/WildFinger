    [SerializeField]
    private UnityEngine.UI.Text _levelText;
    [SerializeField]
    private UnityEngine.UI.Text _bpmText;
    [SerializeField]
    private UnityEngine.UI.Text _totalMarkerCntText;
    [SerializeField]
    private GameObject _noteGeneratorUnitParent;
    [SerializeField]
    private Color32[] _colors; //0: white, 1: Red

